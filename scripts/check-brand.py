#!/usr/bin/env python3
"""Fail the build on any style value that is not in the brand file (src/brand/DESIGN.md).

    python3 scripts/check-brand.py [--surface dashboard|site|all] [files...]

Prints one line per problem, `file:line value reason`, and exits 1 when there is any.
With no files it scans the surface's own files; with files it checks exactly those
(a Stitch export is validated this way, under the dashboard rules unless --surface site).

Dashboard rules (files under src/scripts/courses/dashboard/, `margin.css` excluded):
  - a colour literal (hex, rgb(), hsl(), oklch(), a named colour other than
    transparent / currentColor / inherit) anywhere: colours come from `var(--m-*)`
  - font-family names not in `typography`
  - font-size in px that is not a `typography` size
  - border-radius not in `rounded`
  - var(--m-x) where x is not generated by gen-brand-tokens.py
Site rules (site/, `margin-tokens.css` excluded): the site has no type-size or radius
table and writes many component colours in its own OKLCH system, so only hex, rgb(),
hsl() and named colours (colours outside that system), font-family names outside
`site.fonts` plus `typography`, and unknown var(--m-x) are flagged.

Stdlib only. No model call.
"""
from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Set, Tuple

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "src" / "brand" / "DESIGN.md"
DASH_DIR = ROOT / "src" / "scripts" / "courses" / "dashboard"
SITE_DIR = ROOT / "site"
SKIP_NAMES = {"margin.css", "margin-tokens.css"}

