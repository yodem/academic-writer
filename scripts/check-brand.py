# properties whose value may be (or contain) a named colour
COLOUR_PROPS = re.compile(
    r"^(color|background|background-color|border|border-(top|bottom|left|right|inline|block)(-(start|end))?(-color)?|"
    r"border-color|outline|outline-color|fill|stroke|box-shadow|text-shadow|text-decoration|"
    r"text-decoration-color|caret-color|accent-color|column-rule|column-rule-color|stop-color|flood-color|--[\w-]+)$"
)
GENERIC_FAMILIES = {
    "serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui", "ui-serif", "ui-sans-serif",
    "ui-monospace", "inherit", "initial", "unset", "revert",
}
CSS_WIDE = {"inherit", "initial", "unset", "revert"}

HEX = re.compile(r"(?<![&\w#%-])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![\w-])")
FUNC = re.compile(r"(?<![\w-])(rgba?|hsla?|oklch|oklab|lab|lch|hwb|color)\(", re.I)
DECL = re.compile(r"(?<![\w-])((?:--)?[\w-]+)\s*:\s*([^;{}\n]*(?:\([^)]*\)[^;{}\n]*)*)")
VARM = re.compile(r"var\(\s*(--m-[\w-]+)")
DEFM = re.compile(r"(?<![\w-])(--m-[\w-]+)\s*:")


def _load_gen():
    spec = importlib.util.spec_from_file_location("gen_brand_tokens", ROOT / "scripts" / "gen-brand-tokens.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["gen_brand_tokens"] = mod
    spec.loader.exec_module(mod)
    return mod


class Brand:
    def __init__(self) -> None:
        gen = _load_gen()
        data = gen.parse_brand(BRAND.read_text(encoding="utf-8"))
        self.names: Set[str] = set(gen.generated_names(data))
        self.families: Set[str] = {t["fontFamily"] for t in data["typography"].values()}
        self.sizes: Set[str] = {t["fontSize"] for t in data["typography"].values()}
        self.radii: Set[str] = {self._norm_len(v) for v in data["rounded"].values()}
        site_fonts: Set[str] = set()
        for stack in data["site"]["fonts"].values():
            site_fonts.update(_family_names(stack))
        self.site_families: Set[str] = site_fonts | self.families

    @staticmethod
    def _norm_len(v: str) -> str:
        return "0" if v.strip() in ("0", "0px") else v.strip()


Problem = Tuple[str, int, str, str]  # file, line, value, reason


def _family_names(value: str) -> List[str]:
    out = []
    for part in value.split(","):
        part = part.strip().strip("'\"").strip()
        if part:
            out.append(part)
    return out


def _blank_comments(text: str, js: bool) -> str:
    """Replace comments with spaces, keeping newlines so line numbers survive."""
    def blank(m: "re.Match[str]") -> str:
        return re.sub(r"[^\n]", " ", m.group(0))
    text = re.sub(r"/\*.*?\*/", blank, text, flags=re.S)
    if js:
        text = re.sub(r"(?m)^\s*//.*$", blank, text)
    else:
        text = re.sub(r"<!--.*?-->", blank, text, flags=re.S)
    return text


def _blank_urls(text: str) -> str:
    def blank(m: "re.Match[str]") -> str:
        return "url(" + re.sub(r"[^\n]", " ", m.group(1)) + ")"
    return re.sub(r"url\(([^)]*)\)", blank, text)


def _line_of(text: str, pos: int, base: int) -> int:
    return base + text.count("\n", 0, pos)


def check_style_text(text: str, file: str, base_line: int, brand: Brand, surface: str) -> List[Problem]:
    """Rules over CSS-like text (a stylesheet, a <style> body, a style attribute, a JS style string)."""
    probs: List[Problem] = []
    text = _blank_urls(text)
    # a mask only reads alpha: its #000 / transparent stops are not visible colours
    text = re.sub(r"((?<![\w-])(?:-webkit-)?mask(?:-image)?\s*:)([^;}]*)",
                  lambda m: m.group(1) + re.sub(r"[^\n]", " ", m.group(2)), text)
    dash = surface == "dashboard"
    # colour literals
    for m in HEX.finditer(text):
        probs.append((file, _line_of(text, m.start(), base_line), m.group(0), "colour literal (use var(--m-*))"))
    for m in FUNC.finditer(text):
        fn = m.group(1).lower()
        if not dash and fn in ("oklch", "oklab", "lab", "lch", "color", "hwb"):
            continue
        end = text.find(")", m.end())
        val = text[m.start():(end + 1 if end != -1 else m.end())]
        probs.append((file, _line_of(text, m.start(), base_line), val, "colour literal (use var(--m-*))"))
    # declarations
    for m in DECL.finditer(text):
        prop, val = m.group(1), m.group(2).strip()
        line = _line_of(text, m.start(), base_line)
        if prop.startswith("--m-"):
            if "--m-" + prop[4:] not in brand.names:
                probs.append((file, line, prop, "unknown token (not generated from the brand file)"))
            continue
        if COLOUR_PROPS.match(prop):
            for word in re.findall(r"(?<![\w#-])[a-zA-Z]+(?![\w(-])", re.sub(r"var\([^)]*\)|[\w-]+\([^)]*\)", " ", val)):
                if word.lower() in NAMED_COLOURS:
                    probs.append((file, line, word, "colour literal (named colour; use var(--m-*))"))
        if prop == "font-family":
            allowed = brand.families if dash else brand.site_families
            for name in _family_names(re.sub(r"var\([^)]*\)", "", val)):
                if name.lower() in GENERIC_FAMILIES or name in allowed:
                    continue
                probs.append((file, line, name, "font-family not in the brand file"))
        elif dash and prop == "font-size":
            if re.fullmatch(r"\d+(\.\d+)?px", val) and val not in brand.sizes:
                probs.append((file, line, val, "font-size not in the brand typography table"))
        elif dash and prop.endswith("radius"):
            for tok in re.split(r"[\s/]+", re.sub(r"var\([^)]*\)", "", val).strip()):
                if not tok or tok in CSS_WIDE or tok == "!important":
                    continue
                if Brand._norm_len(tok) not in brand.radii:
                    probs.append((file, line, tok, "border-radius not in the brand file"))
    return probs


def _var_problems(text: str, file: str, base_line: int, brand: Brand) -> List[Problem]:
    out = []
    for m in VARM.finditer(text):
        if m.group(1) not in brand.names:
            out.append((file, _line_of(text, m.start(), base_line), m.group(1), "unknown token (not generated from the brand file)"))
    return out


def _js_strings(text: str) -> Iterable[Tuple[str, int]]:
    for m in re.finditer(r"'((?:\\.|[^'\\\n])*)'|\"((?:\\.|[^\"\\\n])*)\"|`((?:\\.|[^`\\])*)`", text):
        body = next(g for g in m.groups() if g is not None)
        yield body, text.count("\n", 0, m.start()) + 1


def check_file(path: Path, brand: Brand, surface: str) -> List[Problem]:
    rel = str(path.relative_to(ROOT)) if path.is_absolute() and ROOT in path.parents else str(path)
    text = path.read_text(encoding="utf-8")
    ext = path.suffix.lower()
    probs: List[Problem] = []
    if ext == ".css":
        clean = _blank_comments(text, js=False)
        probs += check_style_text(clean, rel, 1, brand, surface)
        probs += _var_problems(clean, rel, 1, brand)
    elif ext in (".html", ".htm"):
        clean = _blank_comments(text, js=False)
        for m in re.finditer(r"<style[^>]*>(.*?)</style>", clean, re.S | re.I):
            base = clean.count("\n", 0, m.start(1)) + 1
            probs += check_style_text(m.group(1), rel, base, brand, surface)
        for m in re.finditer(r"\sstyle\s*=\s*\"([^\"]*)\"|\sstyle\s*=\s*'([^']*)'", clean, re.I):
            body = m.group(1) if m.group(1) is not None else m.group(2)
            base = clean.count("\n", 0, m.start()) + 1
            probs += check_style_text(body, rel, base, brand, surface)
        for m in re.finditer(r"\s(?:fill|stroke|stop-color|flood-color)\s*=\s*\"([^\"]*)\"", clean, re.I):
            val = m.group(1).strip()
            line = clean.count("\n", 0, m.start()) + 1
            if val and val.lower() not in ("none", "currentcolor", "transparent", "inherit", "context-stroke", "context-fill") and not val.startswith("url("):
                probs.append((rel, line, val, "colour literal (SVG attribute; use var(--m-*))"))
        for m in re.finditer(r"<script(?![^>]*\bsrc=)[^>]*>(.*?)</script>", clean, re.S | re.I):
            base = clean.count("\n", 0, m.start(1)) + 1
            probs += _check_js(_blank_comments(m.group(1), js=True), rel, base, brand, surface)
        probs += _var_problems(clean, rel, 1, brand)
    elif ext in (".js", ".mjs"):
        probs += _check_js(_blank_comments(text, js=True), rel, 1, brand, surface)
    return probs


def _check_js(text: str, file: str, base_line: int, brand: Brand, surface: str) -> List[Problem]:
    probs: List[Problem] = []
    for body, line in _js_strings(text):
        probs += check_style_text(body, file, base_line + line - 1, brand, surface)
        probs += _var_problems(body, file, base_line + line - 1, brand)
    return probs


def surface_files(surface: str) -> List[Path]:
    def walk(base: Path, exts: Tuple[str, ...]) -> List[Path]:
        return sorted(p for p in base.rglob("*") if p.is_file() and p.suffix.lower() in exts and p.name not in SKIP_NAMES)
    if surface == "dashboard":
        return walk(DASH_DIR, (".css", ".html", ".js")) if DASH_DIR.exists() else []
    return walk(SITE_DIR, (".css", ".html", ".js"))


def main(argv: List[str]) -> int:
    surface = "all"
    files: List[str] = []
    it = iter(argv)
    for a in it:
        if a == "--surface":
            surface = next(it, "")
        elif a.startswith("--surface="):
            surface = a.split("=", 1)[1]
        elif a in ("-h", "--help"):
            print(__doc__)
            return 0
        else:
            files.append(a)
    if surface not in ("dashboard", "site", "all"):
        print("--surface must be dashboard, site or all", file=sys.stderr)
        return 2
    brand = Brand()
    targets: List[Tuple[Path, str]] = []
    if files:
        rules = "site" if surface == "site" else "dashboard"
        targets = [(Path(f).resolve(), rules) for f in files]
    else:
        for s in (("dashboard", "site") if surface == "all" else (surface,)):
            targets += [(p, s) for p in surface_files(s)]
    problems: List[Problem] = []
    for path, rules in targets:
        if path.name in SKIP_NAMES:
            continue
        problems += check_file(path, brand, rules)
    for file, line, value, reason in sorted(set(problems), key=lambda p: (p[0], p[1], p[2])):
        print("%s:%d %s %s" % (file, line, value, reason))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
