#!/usr/bin/env python3
"""Generate CSS custom properties from the brand file (src/brand/DESIGN.md).

    python3 scripts/gen-brand-tokens.py            write the two generated files
    python3 scripts/gen-brand-tokens.py --check    exit 1 with a diff when they are stale

Outputs:
  src/scripts/courses/dashboard/margin.css   --m-<token> properties for the dashboard
  site/assets/css/margin-tokens.css          the site's exact existing property names

Stdlib only. The frontmatter is a small YAML subset (block maps by indentation, inline
{} maps, [] lists, quoted and plain scalars, # comments), parsed here so nothing else
has to be installed. No model call.
"""
from __future__ import annotations

import difflib
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "src" / "brand" / "DESIGN.md"
DASH_OUT = ROOT / "src" / "scripts" / "courses" / "dashboard" / "margin.css"
SITE_OUT = ROOT / "site" / "assets" / "css" / "margin-tokens.css"

HEADER = "/* GENERATED by scripts/gen-brand-tokens.py from src/brand/DESIGN.md. Do not edit; edit the brand file. */\n"


# ---------------------------------------------------------------- YAML subset


def _strip_comment(line: str) -> str:
    """Remove a trailing '# comment' that sits outside quotes."""
    quote = ""
    for i, ch in enumerate(line):
        if quote:
            if ch == quote:
                quote = ""
        elif ch in "'\"":
            quote = ch
        elif ch == "#" and (i == 0 or line[i - 1] in " \t"):
            return line[:i]
    return line


class _Inline:
    """Recursive descent over one inline value: scalar, {map} or [list]."""

    def __init__(self, text: str) -> None:
        self.s = text
        self.i = 0

    def ws(self) -> None:
        while self.i < len(self.s) and self.s[self.i] in " \t":
            self.i += 1

    def value(self) -> Any:
        self.ws()
        if self.i >= len(self.s):
            return ""
        ch = self.s[self.i]
        if ch == "{":
            return self.map()
        if ch == "[":
            return self.list()
        return self.scalar(",}]")

    def scalar(self, stops: str) -> str:
        self.ws()
        if self.i < len(self.s) and self.s[self.i] in "'\"":
            q = self.s[self.i]
            self.i += 1
            out = []
            while self.i < len(self.s):
                c = self.s[self.i]
                if c == q:
                    if q == "'" and self.s[self.i + 1:self.i + 2] == "'":
                        out.append("'")
                        self.i += 2
                        continue
                    self.i += 1
                    break
                out.append(c)
                self.i += 1
            return "".join(out)
        start = self.i
        while self.i < len(self.s) and self.s[self.i] not in stops:
            self.i += 1
        return self.s[start:self.i].strip()

    def map(self) -> Dict[str, Any]:
        self.i += 1
        out: Dict[str, Any] = {}
        while True:
            self.ws()
            if self.i >= len(self.s):
                raise ValueError("unterminated {")
            if self.s[self.i] == "}":
                self.i += 1
                return out
            key = self.scalar(":,}")
            self.ws()
            if self.s[self.i:self.i + 1] != ":":
                raise ValueError("expected ':' after %r" % key)
            self.i += 1
            out[key] = self.value()
            self.ws()
            if self.s[self.i:self.i + 1] == ",":
                self.i += 1

    def list(self) -> List[Any]:
        self.i += 1
        out: List[Any] = []
        while True:
            self.ws()
            if self.i >= len(self.s):
                raise ValueError("unterminated [")
            if self.s[self.i] == "]":
                self.i += 1
                return out
            out.append(self.value())
            self.ws()
            if self.s[self.i:self.i + 1] == ",":
                self.i += 1


def _split_key(line: str) -> Tuple[str, str]:
    """'key: rest' -> (key, rest); the key may be quoted or start with '--'."""
    if line[:1] in "'\"":
        p = _Inline(line)
        key = p.scalar(":")
        rest = line[p.i:]
        if not rest.startswith(":"):
            raise ValueError("bad key line: %r" % line)
        return key, rest[1:].strip()
    idx = line.index(":")
    return line[:idx].strip(), line[idx + 1:].strip()


def parse_yaml(text: str) -> Dict[str, Any]:
    rows: List[Tuple[int, str]] = []
    for raw in text.split("\n"):
        line = _strip_comment(raw).rstrip()
        if not line.strip():
            continue
        rows.append((len(line) - len(line.lstrip(" ")), line.strip()))

    def block(pos: int, indent: int) -> Tuple[Dict[str, Any], int]:
        out: Dict[str, Any] = {}
        while pos < len(rows) and rows[pos][0] >= indent:
            ind, line = rows[pos]
            if ind != indent:
                raise ValueError("bad indentation near %r" % line)
            key, rest = _split_key(line)
            pos += 1
            if rest == "":
                if pos < len(rows) and rows[pos][0] > indent:
                    out[key], pos = block(pos, rows[pos][0])
                else:
                    out[key] = ""
            else:
                out[key] = _Inline(rest).value()
        return out, pos

    parsed, _ = block(0, 0)
    return parsed


def parse_brand(text: str) -> Dict[str, Any]:
    """Frontmatter of the brand file as a dict."""
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError("brand file has no frontmatter")
    return parse_yaml(m.group(1))


# ---------------------------------------------------------------- generation


def _generic(family: str) -> str:
    return "serif" if "Libre" in family else "sans-serif"


def _dash_props(brand: Dict[str, Any]) -> Tuple[Dict[str, str], Dict[str, str]]:
    """(light-and-static props, dark overrides) for the dashboard, keyed by property name."""
    light: Dict[str, str] = {}
    for k, v in brand["colors"].items():
        light["--m-%s" % k] = v
    for role, t in brand["typography"].items():
        fam = t["fontFamily"]
        light["--m-%s-font" % role] = '"%s", %s' % (fam, _generic(fam))
        light["--m-%s-size" % role] = t["fontSize"]
        light["--m-%s-weight" % role] = t["fontWeight"]
        light["--m-%s-leading" % role] = t["lineHeight"]
    for k, v in brand["spacing"].items():
        light["--m-%s" % k] = v
    for k, v in brand["rounded"].items():
        light["--m-r-%s" % k] = v
    dark = {"--m-%s" % k: v for k, v in brand["dark"].items()}
    return light, dark


def generated_names(brand: Dict[str, Any]) -> List[str]:
    """Every --m-* property the dashboard file defines (for check-brand.py)."""
    light, dark = _dash_props(brand)
    return sorted(set(light) | set(dark))


def _block(selector: str, props: Dict[str, str], indent: str = "") -> List[str]:
    out = ["%s%s {" % (indent, selector)]
    for k, v in props.items():
        out.append("%s  %s: %s;" % (indent, k, v))
    out.append("%s}" % indent)
    return out


def render_dashboard(brand: Dict[str, Any]) -> str:
    light, dark = _dash_props(brand)
    light = dict(light)
    light["color-scheme"] = "light"
    dark = dict(dark)
    dark["color-scheme"] = "dark"
    lines = [HEADER.rstrip("\n")]
    lines += _block(":root", light)
    lines.append("@media (prefers-color-scheme: dark) {")
    lines += _block(':root:not([data-theme="light"])', dark, "  ")
    lines.append("}")
    lines += _block(':root[data-theme="dark"]', dark)
    return "\n".join(lines) + "\n"


def render_site(brand: Dict[str, Any]) -> str:
    site = brand["site"]
    light = site["colors"]["light"]
    dark = site["colors"]["dark"]
    other = dict(site["other"])
    other.update(site["fonts"])
    lines = [HEADER.rstrip("\n")]
    lines += _block(":root", light)
    lines.append("@media (prefers-color-scheme: dark) {")
    lines += _block(':root:not([data-theme="light"])', dark, "  ")
    lines.append("}")
    lines += _block(':root[data-theme="dark"]', dark)
    lines += _block(":root", other)
    return "\n".join(lines) + "\n"


def outputs() -> Dict[Path, str]:
    brand = parse_brand(BRAND.read_text(encoding="utf-8"))
    return {DASH_OUT: render_dashboard(brand), SITE_OUT: render_site(brand)}


def main(argv: List[str]) -> int:
    check = "--check" in argv
    stale = False
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if check:
            if current != text:
                stale = True
                diff = difflib.unified_diff(
                    current.splitlines(), text.splitlines(),
                    "a/%s" % path.relative_to(ROOT), "b/%s" % path.relative_to(ROOT), lineterm="",
                )
                print("\n".join(diff))
        elif current != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print("wrote %s" % path.relative_to(ROOT))
    if check and stale:
        print("stale: run python3 scripts/gen-brand-tokens.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
